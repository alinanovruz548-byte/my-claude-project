"""Перерисовка логотипа «Арт-детектив» (по присланной картинке) -> build/doc/logo_art_detective.png"""
from PIL import Image, ImageDraw

S = 4  # суперсэмплинг
W = 1080
BG, CREAM, GOLD = (30, 30, 30), (245, 239, 230), (212, 166, 74)
ARCS = [
    [(288,232),(400,140),(580,102),(760,150),(880,290),(930,483)],
    [(633,230),(760,290),(850,400),(872,590),(820,730),(740,820),(655,873)],
    [(925,577),(890,740),(780,880),(640,950),(500,977),(340,940),(203,797)],
    [(230,305),(170,420),(148,580),(165,712)],
    [(555,205),(450,190),(330,230),(240,340),(205,490),(215,570),(234,632)],
    [(568,295),(700,320),(800,420),(815,520),(790,610),(750,677)],
    [(503,302),(400,325),(330,380),(303,438)],
    [(275,500),(262,600),(300,700),(400,770),(515,785),(620,760),(700,722)],
    [(272,700),(340,790),(450,860),(572,880)],
    [(378,478),(410,400),(480,350),(550,345),(620,365),(658,411)],
    [(689,458),(712,540),(700,620),(650,690),(580,727),(494,722)],
    [(371,535),(385,610),(420,665),(447,692)],
]


def chaikin(p, n=4):
    for _ in range(n):
        q = [p[0]]
        for a, b in zip(p, p[1:]):
            q += [(.75*a[0]+.25*b[0], .75*a[1]+.25*b[1]), (.25*a[0]+.75*b[0], .25*a[1]+.75*b[1])]
        q.append(p[-1])
        p = q
    return p


im = Image.new("RGB", (W*S, W*S), BG)
d = ImageDraw.Draw(im)
w = 27*S
for arc in ARCS:
    pts = [(x*S, y*S) for x, y in chaikin(arc)]
    dense = []
    for a, b in zip(pts, pts[1:]):
        n = max(1, int(max(abs(b[0]-a[0]), abs(b[1]-a[1])) / (2*S)))
        dense += [(a[0]+(b[0]-a[0])*i/n, a[1]+(b[1]-a[1])*i/n) for i in range(n)]
    dense.append(pts[-1])
    for x, y in dense:
        d.ellipse([x-w/2, y-w/2, x+w/2, y+w/2], fill=CREAM)
c = 540*S; r = 54*S
d.ellipse([c-r, c-r, c+r, c+r], fill=GOLD)
im = im.resize((W, W), Image.LANCZOS)
im.save(r"C:\Users\awright\Desktop\Видео Клод\build\doc\logo_art_detective.png")
