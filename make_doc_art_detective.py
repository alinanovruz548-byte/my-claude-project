def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    s = OxmlElement("w:shd")
    s.set(qn("w:val"), "clear"); s.set(qn("w:color"), "auto"); s.set(qn("w:fill"), hexcolor)
    tcPr.append(s)


def para(text="", bold=False, size=None, color=None, italic=False, after=4, align=None, style=None):
    p = d.add_paragraph(style=style)
    p.paragraph_format.space_after = Pt(after)
    if align: p.alignment = align
    if text:
        r = p.add_run(text); r.bold = bold; r.italic = italic
        if size: r.font.size = Pt(size)
        if color: r.font.color.rgb = color
    return p


def h(text, color=BLUE, size=16):
    p = para(text, bold=True, size=size, color=color, after=4)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.keep_with_next = True
    return p


def bullet(text, lead=None):
    p = d.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(2)
    if lead:
        r = p.add_run(lead); r.bold = True
    p.add_run(text)
    return p


def table(rows, widths, header=True, fill="2B3FA0"):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, txt in enumerate(row):
            c = t.cell(i, j)
            c.width = Cm(widths[j])
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            r = p.add_run(txt); r.font.size = Pt(10)
            if header and i == 0:
                r.bold = True; r.font.color.rgb = RGBColor(255, 255, 255); shade(c, fill)
            elif j == 0:
                r.bold = True
    d.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


